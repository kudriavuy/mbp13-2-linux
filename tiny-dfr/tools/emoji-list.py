#!/usr/bin/python3 -I
"""The emoji panel's list (tiny-dfr patch 0019) from Unicode's emoji-test.txt
(https://unicode.org/Public/emoji/latest/emoji-test.txt):
    emoji-list.py <emoji-test.txt> <out emoji.txt> [max version, e.g. 16.0]
Groups in the macOS Touch Bar order (Smileys & People one group), only
fully-qualified emoji, no skin tone variants (the plain one is kept), nothing
newer than the version the font can draw. Output: "@<group> <icon>" lines,
each followed by one line of the group's emoji separated by spaces."""
import re
import sys

GROUPS = [  # (ours, Unicode's, the category key's emoji)
    ("smileys", ("Smileys & Emotion", "People & Body"), "\U0001F600"),
    ("animals", ("Animals & Nature",), "\U0001F43B"),
    ("food", ("Food & Drink",), "\U0001F354"),
    ("activity", ("Activities",), "⚽"),
    ("travel", ("Travel & Places",), "\U0001F697"),
    ("objects", ("Objects",), "\U0001F4A1"),
    ("symbols", ("Symbols",), "\U0001F523"),
    ("flags", ("Flags",), "\U0001F3F3️"),
]
TONES = set(range(0x1F3FB, 0x1F400))
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s")


def main(src, out, max_version="99"):
    top = tuple(int(p) for p in max_version.split("."))
    found = {u: [] for _, us, _ in GROUPS for u in us}
    group = None
    for line in open(src, encoding="utf-8"):
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        m = LINE.match(line)
        if not m or group not in found:
            continue
        cps = [int(c, 16) for c in m.group(1).split()]
        if TONES & set(cps):
            continue
        if tuple(int(p) for p in m.group(2).split(".")) > top:
            continue
        found[group].append("".join(map(chr, cps)))
    with open(out, "w", encoding="utf-8") as f:
        f.write(f"# generated by emoji-list.py from emoji-test.txt, emoji <= {max_version}\n")
        for name, us, icon in GROUPS:
            f.write(f"@{name} {icon}\n")
            f.write(" ".join(e for u in us for e in found[u]) + "\n")
    print({n: sum(len(found[u]) for u in us) for n, us, _ in GROUPS})


if __name__ == "__main__":
    main(*sys.argv[1:])
