#!/usr/bin/env python3
"""Regenerate srom_tables.py from Broadcom's bcmsrom_fmt.h / bcmsrom_tbl.h.

The headers are not kept here (get them from bcmdhd, e.g.
https://fuchsia.googlesource.com/third_party/bcmdhd/ include/). The generated
file is just a list of (name, revmask, flags, word offset, mask) facts.
The tables are kept whole (all revisions, None for entries that cannot be
resolved), because SRFL_MORE chains must stay aligned.

usage: gen_srom_table.py <bcmsrom_fmt.h> <bcmsrom_tbl.h> > srom_tables.py
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srom2nvram import load_defines, load_table, PATHS

REVS = (12,)
raw, ev = load_defines(sys.argv[1], sys.argv[2])
print('"""SROM variable tables for BCM43602 (SROM rev %s).' % ",".join(map(str, REVS)))
print()
print("Generated by gen_srom_table.py from Broadcom bcmdhd bcmsrom_tbl.h /")
print('bcmsrom_fmt.h (Broadcom, dual GPL-2.0). Do not edit by hand."""')
for name in ("pci_sromvars", "perpath_pci_sromvars"):
    tab = load_table(sys.argv[2], name, ev)
    keep = tab
    print(f"{name.upper()} = [")
    for e in keep:
        print(f"    {e!r},")
    print("]")
for r in REVS:
    p0, p1, n = (ev(x) for x in PATHS[r])
    print(f"PATHS_{r} = ({p0}, {p1 - p0}, {n})  # first path word, stride, paths")
print(f"CRCREV_WORD = {ev('SROM12_CRCREV')}")
