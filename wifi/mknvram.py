#!/usr/bin/env python3
"""Build the brcmfmac NVRAM for this MacBookPro13,2 from its own SROM image.

The image (read by read_srom.py) is checked first: 1024 words, Apple
signature 0x9999 at word 64, SROM rev 12, CRC8 OK, 14e4:43ba with subsystem
vendor 0x106b. The variables are decoded with srom_tables.py (Broadcom's
_initvars_srom_pci() logic, see srom2nvram.walk) and then laid out as the
recipe says. The output contains the MAC address and calibration data of
this board: it belongs in /lib/firmware only, never in git.

usage: mknvram.py <srom.bin> <recipe> > nvram.txt
"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srom2nvram import walk
import srom_tables as T

CRC8_TABLE = []
for i in range(256):  # ssb/bcm CRC8, same table as ssb_crc8() in the kernel
    c = i
    for _ in range(8):
        c = (c >> 1) ^ 0xab if c & 1 else c >> 1
    CRC8_TABLE.append(c)


def crc8(words):
    c = 0xff
    for w in words[:-1]:
        c = CRC8_TABLE[c ^ (w & 0xff)]
        c = CRC8_TABLE[c ^ (w >> 8)]
    c = CRC8_TABLE[c ^ (words[-1] & 0xff)]
    return c ^ 0xff


def main():
    data = open(sys.argv[1], "rb").read()
    if len(data) != 2048:
        sys.exit(f"SROM image must be 1024 words, got {len(data)} bytes")
    w = list(struct.unpack("<1024H", data))
    rev = w[T.CRCREV_WORD] & 0xff
    checks = {
        "Apple signature 0x9999 at word 64": w[64] == 0x9999,
        "SROM rev 12": rev == 12 and w[1023] & 0xff == 12,
        "CRC8": crc8(w) == w[1023] >> 8,
    }
    bad = [k for k, ok in checks.items() if not ok]
    if bad:
        sys.exit("SROM image rejected: " + ", ".join(bad))

    srom = {}
    for nm, v in walk(T.PCI_SROMVARS, w, rev):
        srom.setdefault(nm, v)
    p0, stride, npath = T.PATHS_12
    for p in range(npath):
        for nm, v in walk(T.PERPATH_PCI_SROMVARS, w, rev, base=p0 + p * stride, suffix=str(p)):
            srom.setdefault(nm, v)
    if srom.get("devid") != "0x43ba" or srom.get("subvid") != "0x106b":
        sys.exit(f"not the Apple BCM43602 board: devid {srom.get('devid')} subvid {srom.get('subvid')}")

    out = [f"# generated by mknvram.py from this machine's SROM ({os.path.basename(sys.argv[2])})"]
    for line in open(sys.argv[2]):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        k, v = line.split("=", 1)
        if v == "@srom":
            if k not in srom:
                sys.exit(f"recipe wants {k} from the SROM, but it is not there")
            v = srom[k]
        out.append(f"{k}={v}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
